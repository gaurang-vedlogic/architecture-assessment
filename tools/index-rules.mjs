#!/usr/bin/env node
// Regenerates rules/INDEX.md by parsing every rule block in rules/**/*.md.
// Run: npm run index-rules
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RULES = path.join(ROOT, 'rules');

/** Recursively collect .md files under rules/, excluding README/INDEX. */
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return walk(p);
    if (!e.name.endsWith('.md')) return [];
    if (e.name === 'README.md' || e.name === 'INDEX.md') return [];
    return [p];
  });
}

const FIELD = (body, label) => {
  const m = body.match(new RegExp(`\\*\\*${label}:\\*\\*\\s*([^\\n|]+)`, 'i'));
  return m ? m[1].trim().replace(/\s+$/, '') : '';
};

function parseFile(file) {
  const text = fs.readFileSync(file, 'utf8');
  const rel = path.relative(ROOT, file).replace(/\\/g, '/');
  const blocks = text.split(/^### /m).slice(1);
  return blocks.map((block) => {
    const [heading, ...rest] = block.split('\n');
    const body = rest.join('\n');
    const [, id, title] = heading.match(/^([A-Z0-9-]+)\s+—\s+(.*)$/) ?? [, heading.trim(), ''];
    // "Criticality" and "Priority" share one bullet: **Criticality:** High | **Priority:** P0 | **Phase:** 1
    const cpp = body.match(/\*\*Criticality:\*\*\s*(\w+)\s*\|\s*\*\*Priority:\*\*\s*(P\d)\s*\|\s*\*\*Phase:\*\*\s*(\d)/);
    return {
      id,
      title: title.trim(),
      file: rel,
      dimension: FIELD(body, 'Dimension'),
      layer: FIELD(body, 'Layer'),
      criticality: cpp?.[1] ?? '',
      priority: cpp?.[2] ?? '',
      phase: cpp?.[3] ?? '',
      effort: FIELD(body, 'Effort'),
    };
  });
}

const files = walk(RULES).sort();
const rules = files.flatMap(parseFile);

const byPack = new Map();
for (const r of rules) {
  if (!byPack.has(r.file)) byPack.set(r.file, []);
  byPack.get(r.file).push(r);
}

const counts = rules.reduce((acc, r) => ((acc[r.dimension] = (acc[r.dimension] ?? 0) + 1), acc), {});

let out = `# Rule Index

Generated by \`npm run index-rules\` — do not edit by hand.

**${rules.length} rules** across **${byPack.size} packs**.

| Dimension | Rules |
| --- | --- |
${Object.entries(counts)
  .sort((a, b) => b[1] - a[1])
  .map(([d, n]) => `| ${d || '—'} | ${n} |`)
  .join('\n')}

`;

for (const [file, list] of byPack) {
  out += `\n## \`${file}\`\n\n| ID | Rule | Dimension | Layer | Crit. | Pri. | Phase | Effort |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n`;
  for (const r of list) {
    out += `| \`${r.id}\` | ${r.title} | ${r.dimension} | ${r.layer} | ${r.criticality} | ${r.priority} | ${r.phase} | ${r.effort} |\n`;
  }
}

fs.writeFileSync(path.join(RULES, 'INDEX.md'), out);
console.log(`Wrote rules/INDEX.md — ${rules.length} rules, ${byPack.size} packs.`);

// Warn on duplicate IDs — these must never happen.
const seen = new Map();
for (const r of rules) {
  if (seen.has(r.id)) console.error(`DUPLICATE ID ${r.id}: ${seen.get(r.id)} and ${r.file}`);
  seen.set(r.id, r.file);
}
